def entry(table: int, weapon_id: int) -> tuple[int, int]:
    """(state, damage) for a weapon in a table. `weapon_id` is 1-based, as the
    workbook numbers them."""
    off = table * TABLE_STRIDE + (weapon_id - 1) * 2
    return VANILLA[off], VANILLA[off + 1]


def is_scalable(state: int, damage: int) -> bool:
    return (state != INERT_STATE
            and damage != NO_DAMAGE
            and damage != INSTANT_KILL)


def scale_damage(damage: int, scale: float) -> int:
    """Scale one damage byte, rounded to nearest, clamped, never zero."""
    scaled = int(damage * scale + 0.5)
    return max(DAMAGE_MIN, min(DAMAGE_MAX, scaled))


def damage_edits(scales: dict[str, float]
                 ) -> list[tuple[str, int, str, bytes, bytes]]:
    """Disc edits applying a per-group scale across all 46 tables.

    Only the DAMAGE byte is ever written; the state byte beside it decides
    whether an interaction happens at all and is none of this option's
    business. Entries that come out unchanged are omitted, so the patch
    carries only real differences.
    """
    from .disc import REGION_EXE

    out: list[tuple[str, int, str, bytes, bytes]] = []
    for group, weapon_ids in WEAPON_GROUPS.items():     # dict order
        scale = scales.get(group)
        if scale is None:
            continue
        for table in range(TABLE_COUNT):
            for weapon_id in weapon_ids:
                state, damage = entry(table, weapon_id)
                if not is_scalable(state, damage):
                    continue
                new = scale_damage(damage, scale)
                if new == damage:
                    continue
                address = (TABLE_BASE + table * TABLE_STRIDE
                           + (weapon_id - 1) * 2 + 1)
                out.append((f"{group} dmg t{table} w{weapon_id}",
                            address, REGION_EXE,
                            bytes([damage]), bytes([new])))
    return out
