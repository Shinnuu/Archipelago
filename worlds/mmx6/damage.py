"""Damage tables - the data behind `weapon_damage`.

X6 keeps 46 damage tables in the static EXE, contiguous from 0x800741FC, each
exactly 80 two-byte entries: a state byte and a damage byte. The table is
chosen by what is being hit and indexed by WEAPON ID - `movb r5,[r16+1h]`
("current weapon ID") feeding `mov r3,[r17+58h]` ("current damage table") in
the hit-detection routine at 0x80031474.

That layout is what makes randomizing safe. A boss's weakness IS its row in
its own table, so scaling one weapon by the same factor across every table
changes how strong that weapon is without flattening which bosses it is good
against. Rolling each table entry independently would erase the weakness
system outright.

Everything here is byte-verified against a real disc: 44 of the 45 tables the
X6 Tweaks Workbook names match exactly, the 46th is one the workbook does not
list, and the whole region is reproduced in VANILLA below so a patch built for
one dump cannot silently corrupt another.
"""

TABLE_BASE = 0x800741FC
TABLE_COUNT = 46
TABLE_ENTRIES = 80
TABLE_STRIDE = TABLE_ENTRIES * 2        # 0xA0

# Damage that must never be scaled:
#   0x00  deals no damage at all - scaling it can only turn "harmless" into
#         "harmful", which is not what this option is for.
#   0x7F  the instant-kill marker. A crush or a pit stays a crush or a pit.
# and any entry whose STATE byte is 0xFF, which means the interaction is
# inert. Thirteen of those carry a non-zero damage byte, so skipping on
# damage alone is NOT enough - that is why the state byte is kept here too.
NO_DAMAGE = 0x00
INSTANT_KILL = 0x7F
INERT_STATE = 0xFF

# Damage never rolls to zero (the game already floors real damage at 1) and
# never rolls INTO the instant-kill marker.
DAMAGE_MIN = 0x01
DAMAGE_MAX = 0x7E

# Scale bands, inherited from the X5 world so the two play the same way.
SCALE_BANDS = {
    "weak":    (0.50, 0.90),
    "regular": (0.80, 1.30),
    "strong":  (1.20, 2.00),
    "chaotic": (0.25, 2.50),
}

